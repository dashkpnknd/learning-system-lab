import os
from PIL import Image


def create_test_video_html():
    if not os.path.exists("multimedia"):
        os.makedirs("multimedia")

    video_html = '''
    <!DOCTYPE html>
    <html>
    <head>
        <meta charset="utf-8">
        <style>
            body { margin: 0; padding: 0; background: #000; color: #fff; font-family: Arial, sans-serif; }
            .wrap { padding: 40px; text-align: center; }
        </style>
    </head>
    <body>
        <div class="wrap">
            <h2>Локальное видео не настроено</h2>
            <p>Укажите реальную ссылку на YouTube или путь к видеофайлу.</p>
        </div>
    </body>
    </html>
    '''

    for html_name in ["video_intro.html", "video_arch.html", "video_prog.html"]:
        html_path = os.path.join("multimedia", html_name)
        if not os.path.exists(html_path):
            with open(html_path, "w", encoding="utf-8") as f:
                f.write(video_html)

    image_files = {
        "it_intro.jpg": "lightblue",
        "computer_architecture.png": "lightgreen",
        "programming.png": "lightyellow"
    }

    for img_file, color in image_files.items():
        img_path = os.path.join("multimedia", img_file)
        if not os.path.exists(img_path):
            img = Image.new('RGB', (500, 300), color=color)
            img.save(img_path)


